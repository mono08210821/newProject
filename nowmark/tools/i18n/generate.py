"""Generates Android string resources from the per-language tables and validates them.

Run: python3 tools/i18n/generate.py   (from the nowmark/ directory or anywhere)
Fails if a key used in code is missing, a language misses a key, or format
placeholders differ between English and a translation.
"""
import importlib, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
SRC = os.path.join(ROOT, "app", "src", "main")
sys.path.insert(0, HERE)

LANGS = {  # module -> values dir qualifier
    "en": "values", "ko": "values-ko", "ja": "values-ja", "zh": "values-zh-rCN", "es": "values-es",
    "pt": "values-pt-rBR", "de": "values-de", "fr": "values-fr", "hi": "values-hi", "ar": "values-ar",
}
UNTRANSLATABLE = {"app_name"}
PH = re.compile(r"%(\d+\$)?[sd]")

def esc(s: str) -> str:
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s

def placeholders(s): return sorted(PH.findall(s)), len(PH.findall(s))

errors = []
tables = {m: importlib.import_module(m) for m in LANGS}
en = tables["en"]

# Keys referenced from code/resources.
used_s, used_p = set(), set()
for d, _, files in os.walk(SRC):
    for f in files:
        if f.endswith((".kt", ".xml")) and "values" not in d:
            t = open(os.path.join(d, f), encoding="utf-8").read()
            used_s |= set(re.findall(r"R\.string\.([a-z0-9_]+)", t)) | set(re.findall(r"@string/([a-z0-9_]+)", t))
            used_p |= set(re.findall(r"R\.plurals\.([a-z0-9_]+)", t))
for k in sorted(used_s - set(en.S)): errors.append(f"missing string key in en: {k}")
for k in sorted(used_p - set(en.P)): errors.append(f"missing plurals key in en: {k}")
unused = sorted(set(en.S) - used_s - UNTRANSLATABLE)
if unused: print("note: unused string keys:", ", ".join(unused))

for m, mod in tables.items():
    if set(mod.S) != set(en.S): errors.append(f"{m}: key mismatch {sorted(set(mod.S) ^ set(en.S))}")
    if set(mod.P) != set(en.P): errors.append(f"{m}: plurals mismatch")
    for k, v in mod.S.items():
        if k in en.S and placeholders(v)[0] != placeholders(en.S[k])[0]:
            errors.append(f"{m}:{k} placeholders {placeholders(v)[0]} != en {placeholders(en.S[k])[0]}")
    for k, q in mod.P.items():
        if "other" not in q: errors.append(f"{m}:{k} plural needs 'other'")
        for qq, v in q.items():
            if "%d" not in v: errors.append(f"{m}:{k}/{qq} plural must contain %d")

if errors:
    print("\n".join(errors)); sys.exit(1)

for m, qual in LANGS.items():
    mod = tables[m]
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by tools/i18n/generate.py. Edit the tables there, not this file. -->",
           "<resources>"]
    for k in en.S:
        if k in UNTRANSLATABLE:
            if m == "en": out.append(f'    <string name="{k}" translatable="false">{esc(mod.S[k])}</string>')
            continue
        fmt = ' formatted="false"' if False else ""
        out.append(f'    <string name="{k}"{fmt}>{esc(mod.S[k])}</string>')
    for k, q in mod.P.items():
        out.append(f'    <plurals name="{k}">')
        for qq in ("zero", "one", "two", "few", "many", "other"):
            if qq in q: out.append(f'        <item quantity="{qq}">{esc(q[qq])}</item>')
        out.append("    </plurals>")
    out.append("</resources>\n")
    d = os.path.join(RES, qual); os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "strings.xml"), "w", encoding="utf-8").write("\n".join(out))
print(f"ok: {len(en.S)} strings, {len(en.P)} plurals, {len(LANGS)} languages")
